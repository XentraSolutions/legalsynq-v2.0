"use client";

import { useCallback, useEffect, useMemo, useState } from "react";
import { useRouter } from "next/navigation";
import {
  useAutoGeneratedReportList,
} from "@/hooks/use-casenote-history";


export default function HistoryNotesPage() {
  const router = useRouter();
  const { data: reports, isLoading: loadingData } = useAutoGeneratedReportList({
    page: 1,
    pageSize: 50,
  });

  return (
    <div className="space-y-4">
      {loadingData ? (
        <div className="overflow-hidden">
          <div className="text-center py-8">
            <div className="inline-block h-5 w-5 animate-spin rounded-full border-2 border-primary border-t-transparent" />
            <p className="text-sm text-gray-400 mt-2">Loading reports...</p>
          </div>
        </div>
      ) : (
        <div>
             <div className="flex justify-between items-center bg-white p-4 rounded-xl border border-gray-200 mb-6">
              <div>
                <h2 className="text-lg font-semibold">Auto Generated Reports</h2>

               <p className="text-sm text-gray-500">
                {reports?.items?.length ? reports?.items?.length + 1: 1} generated templates
               </p>
              </div>
            </div>
        <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
          <div
            onClick={() => router.push(`/lien/reports/auto-generated/notes-history`)}
            className="border border-gray-200 rounded-xl p-3 py-4 bg-white hover:bg-gray-50 cursor-pointer transition-colors"
          >
            <div className="text-sm font-medium text-gray-900">
              Case Notes History
            </div>
            <div className="text-xs text-gray-500 mt-1">System Report</div>
          </div>
          {reports &&
            reports.items?.map((r: any) => (
              <div
                key={r.reportId}
                onClick={() =>
                  router.push(`/lien/reports/auto-generated/${r.reportId}`)
                }
                className="border border-gray-200 rounded-xl p-3 bg-white hover:bg-gray-50 cursor-pointer transition-colors"
              >
                <div className="text-sm font-medium text-gray-900">
                  {r.description}
                </div>
                <div className="text-xs text-gray-500 mt-1">System Report</div>
              </div>
            ))}
        </div>
        </div>
      )}
    </div>
  );
}
