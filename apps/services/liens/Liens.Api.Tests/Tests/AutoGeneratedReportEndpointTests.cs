        var rows = Enumerable.Range(0, 101)
            .Select(index => ($"LIEN-BATCH-{index:D3}", new DateOnly(2026, 8, 1)))
            .ToArray();
        await AddWeeklyBccLiensAsync(rows);

        var response = await _client.PostAsync(
            $"/api/liens/reports/auto-generated/{report.Id}/export",
            content: null);

        response.StatusCode.Should().Be(HttpStatusCode.OK);
        var document = await response.Content.ReadFromJsonAsync<JsonDocument>();
        var base64 = document!.RootElement.GetProperty("data")[0].GetProperty("base64").GetString()!;
        var csv = Encoding.UTF8.GetString(Convert.FromBase64String(base64));
        csv.Split("\r\n", StringSplitOptions.None).Should().HaveCount(103);
        csv.Should().Contain("LIEN-BATCH-100");
    }

