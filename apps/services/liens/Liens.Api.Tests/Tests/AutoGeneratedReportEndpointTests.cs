    [Fact]
    public async Task Execute_pages_in_database_and_returns_columns_aligned_with_rows()
    {
        var report = await AddReportAsync(SeedHelper.TenantId, new DateOnly(2026, 8, 17));
        await AddWeeklyBccLiensAsync(
            ("LIEN-PAGE-001", new DateOnly(2026, 8, 1)),
            ("LIEN-PAGE-002", new DateOnly(2026, 8, 2)),
            ("LIEN-PAGE-003", new DateOnly(2026, 8, 3)));

        var response = await _client.PostAsync(
            $"/api/liens/reports/auto-generated/{report.Id}/execute?page=2&pageSize=2",
            content: null);

        response.StatusCode.Should().Be(HttpStatusCode.OK);
        var document = await response.Content.ReadFromJsonAsync<JsonDocument>();
        var root = document!.RootElement;
        root.GetProperty("page").GetInt32().Should().Be(2);
        root.GetProperty("pageSize").GetInt32().Should().Be(2);
        root.GetProperty("totalPages").GetInt32().Should().Be(2);
        root.GetProperty("totalCount").GetInt32().Should().Be(3);
        root.GetProperty("data").GetArrayLength().Should().Be(1);
        root.GetProperty("data")[0].GetProperty("lienId").GetString().Should().Be("LIEN-PAGE-003");

        var columns = root.GetProperty("columns").EnumerateArray().ToArray();
        columns.Should().HaveCount(57);
        columns.Select(column => column.GetProperty("index").GetInt32())
            .Should().Equal(Enumerable.Range(0, 57));
        columns.Select(column => column.GetProperty("key").GetString())
            .Should().OnlyHaveUniqueItems();
        columns.Select(column => column.GetProperty("key").GetString())
            .Should().Equal(root.GetProperty("data")[0]
                .EnumerateObject()
                .Select(property => property.Name));
    }

