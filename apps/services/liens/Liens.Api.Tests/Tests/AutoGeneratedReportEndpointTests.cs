            .Should().Be(legacyDocument.RootElement.GetProperty("schemaVersion").GetInt32());
        canonicalDocument.RootElement.GetProperty("columns").GetRawText()
            .Should().Be(legacyDocument.RootElement.GetProperty("columns").GetRawText());
    }

    [Fact]
    public async Task Export_returns_all_rows_in_column_order_with_formula_safe_csv()
    {
        var report = await AddReportAsync(SeedHelper.TenantId, new DateOnly(2026, 8, 17));
        await AddWeeklyBccLiensAsync(
            ("=2+2", new DateOnly(2026, 8, 1)),
            ("LIEN,\"Q\"", new DateOnly(2026, 8, 2)),
            ("LIEN-Ñ-003", new DateOnly(2026, 8, 3)));

        var canonical = await _client.PostAsync(
            $"/api/liens/reports/auto-generated/{report.Id}/export",
            content: null);
        var legacy = await _client.PostAsync(
            $"/report/auto-generated/{report.Id}/export",
            content: null);

        canonical.StatusCode.Should().Be(HttpStatusCode.OK);
        canonical.Headers.CacheControl?.NoStore.Should().BeTrue();
        var canonicalDocument = await canonical.Content.ReadFromJsonAsync<JsonDocument>();
        var legacyDocument = await legacy.Content.ReadFromJsonAsync<JsonDocument>();
        var item = canonicalDocument!.RootElement.GetProperty("data")[0];
        item.GetProperty("filename").GetString().Should().Be("weekly_bcc_20260817.csv");
        item.GetProperty("export_format").GetString().Should().Be("csv");
        item.GetProperty("base64").GetString()
            .Should().Be(legacyDocument!.RootElement.GetProperty("data")[0].GetProperty("base64").GetString());

        var csv = Encoding.UTF8.GetString(Convert.FromBase64String(item.GetProperty("base64").GetString()!));
        var lines = csv.Split("\r\n", StringSplitOptions.None);
        lines[0].Split(',').Should().HaveCount(57);
        lines[0].Should().StartWith("Plaintiff First Name,Plaintiff Last Name,Plaintiff Date of Birth");
        lines.Should().HaveCount(5);
        csv.Should().Contain("'=2+2");
        csv.Should().Contain("\"LIEN,\"\"Q\"\"\"");
        csv.Should().Contain("LIEN-Ñ-003");
    }

