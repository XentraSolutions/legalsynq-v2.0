            Guid tenantId,
            DateOnly asOfDate,
            int page,
            int pageSize,
            bool includeTotalCount = true,
            CancellationToken ct = default)
        {
            return Task.FromResult(new WeeklyBccReportResult());
        }

        public Task<WeeklyBccExportBatch> GetExportBatchAsync(
            Guid tenantId,
            DateOnly asOfDate,
            WeeklyBccExportCursor? cursor,
            int batchSize,
            CancellationToken ct = default)
        {
            ExportBatchCalls++;
            TenantId = tenantId;
            AsOfDate = asOfDate;
            Cursor = cursor;
            BatchSize = batchSize;
            CancellationToken = ct;
            return Task.FromResult(new WeeklyBccExportBatch([], null));
        }
    }

