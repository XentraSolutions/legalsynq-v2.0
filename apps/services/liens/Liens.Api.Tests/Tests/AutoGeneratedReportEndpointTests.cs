    private async Task<AutoGeneratedReport> AddReportAsync(
        Guid tenantId,
        DateOnly reportDate,
        string apiPath = AutoGeneratedReportDispatcher.CanonicalWeeklyBccPath)
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<LiensDbContext>();
        var report = AutoGeneratedReport.Create(
            tenantId,
            $"weekly_bcc_{reportDate:yyyy-MM-dd}",
            $"Weekly BCC - {reportDate:MM/dd/yyyy}",
            reportDate,
            DateTime.UtcNow,
            apiPath);
        db.AutoGeneratedReports.Add(report);
        await db.SaveChangesAsync();
        return report;
    }

    private async Task AddWeeklyBccLiensAsync(params (string LienNumber, DateOnly PurchaseDate)[] rows)
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<LiensDbContext>();
        var caseEntity = Case.Create(
            SeedHelper.TenantId,
            SeedHelper.OrgId,
            $"CASE-PAGE-{Guid.NewGuid():N}",
            "Page",
            "Test",
            SeedHelper.UserId);
        db.Cases.Add(caseEntity);

        foreach (var row in rows)
        {
            db.Liens.Add(Lien.Create(
                SeedHelper.TenantId,
                SeedHelper.OrgId,
                row.LienNumber,
                LienType.MedicalLien,
                100m,
                SeedHelper.UserId,
                caseId: caseEntity.Id,
                purchaseDate: row.PurchaseDate));
        }

        await db.SaveChangesAsync();
    }

    private sealed class RecordingWeeklyBccReportService : IWeeklyBccReportService
