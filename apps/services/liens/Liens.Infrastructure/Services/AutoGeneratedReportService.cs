using System.Globalization;
using System.Text;
using System.Text.Json;
using Liens.Application.DTOs;
using Liens.Application.Interfaces;
using Liens.Application.Repositories;
using Liens.Domain.Entities;
using Liens.Infrastructure.Options;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Liens.Infrastructure.Services;

public sealed class AutoGeneratedReportService : IAutoGeneratedReportService
{
    internal const int ExportBatchSize = 500;
    private static readonly JsonSerializerOptions CsvJsonOptions = new(JsonSerializerDefaults.Web);
    private readonly IAutoGeneratedReportRepository _reports;
    private readonly IAutoGeneratedReportTenantSource _tenantSource;
    private readonly IAutoGeneratedReportDispatcher _dispatcher;
    private readonly IAutoGeneratedReportExportStreamFactory _streamFactory;
    private readonly TimeProvider _timeProvider;
    private readonly ILogger<AutoGeneratedReportService> _logger;
    private readonly long _exportByteLimit;

    public AutoGeneratedReportService(
        IAutoGeneratedReportRepository reports,
        IAutoGeneratedReportTenantSource tenantSource,
        IAutoGeneratedReportDispatcher dispatcher,
        IAutoGeneratedReportExportStreamFactory streamFactory,
        TimeProvider timeProvider,
        IOptions<AutoGeneratedReportOptions> options,
        ILogger<AutoGeneratedReportService> logger)
    {
        _reports = reports;
        _tenantSource = tenantSource;
        _dispatcher = dispatcher;
        _streamFactory = streamFactory;
        _timeProvider = timeProvider;
        _exportByteLimit = options.Value.ExportSizeLimitMiB * 1024L * 1024L;
        _logger = logger;
    }

    public async Task<AutoGeneratedReportPage> ListAsync(
        Guid tenantId,
        int page,
        int pageSize,
        CancellationToken ct = default)
    {
        var (items, totalCount) = await _reports.ListAsync(tenantId, page, pageSize, ct);
        return new AutoGeneratedReportPage(
            items.Select(ToResponse).ToList(),
            page,
            pageSize,
            totalCount);
    }

    public async Task<AutoGeneratedReportExecutionResult> ExecuteAsync(
        Guid tenantId,
        long reportId,
        int page,
        int pageSize,
        CancellationToken ct = default)
    {
        if (tenantId == Guid.Empty || reportId <= 0)
            return new AutoGeneratedReportExecutionResult(AutoGeneratedReportExecutionStatus.NotFound);

        var report = await _reports.GetByIdAsync(tenantId, reportId, ct);
        if (report is null)
            return new AutoGeneratedReportExecutionResult(AutoGeneratedReportExecutionStatus.NotFound);

        var response = ToResponse(report);
        var definition = _dispatcher.ResolveDefinition(report.ApiPath);
        if (definition is null)
        {
            return new AutoGeneratedReportExecutionResult(
                AutoGeneratedReportExecutionStatus.UnsupportedPath,
                response);
        }

        var weeklyBcc = await _dispatcher.ExecuteAsync(report, page, pageSize, includeTotalCount: true, ct);
        return new AutoGeneratedReportExecutionResult(
            AutoGeneratedReportExecutionStatus.Success,
            response,
            weeklyBcc,
            definition);
    }

    public async Task<AutoGeneratedReportExportResult> ExportAsync(
        Guid tenantId,
        long reportId,
        CancellationToken ct = default)
    {
        if (tenantId == Guid.Empty || reportId <= 0)
            return new AutoGeneratedReportExportResult(AutoGeneratedReportExecutionStatus.NotFound);

        var report = await _reports.GetByIdAsync(tenantId, reportId, ct);
        if (report is null)
            return new AutoGeneratedReportExportResult(AutoGeneratedReportExecutionStatus.NotFound);

        var response = ToResponse(report);
        var definition = _dispatcher.ResolveDefinition(report.ApiPath);
        if (definition is null)
        {
            return new AutoGeneratedReportExportResult(
                AutoGeneratedReportExecutionStatus.UnsupportedPath,
                response);
        }

        var stream = _streamFactory.Create();
        try
        {
            if (!await TryAppendCsvLineAsync(
                    stream,
                    definition.Columns.Select(column => column.Label),
                    _exportByteLimit,
                    ct))
            {
                await stream.DisposeAsync();
                return new AutoGeneratedReportExportResult(
                    AutoGeneratedReportExecutionStatus.Success,
                    response,
                    SizeLimitExceeded: true);
            }

            WeeklyBccExportCursor? cursor = null;
            do
            {
                ct.ThrowIfCancellationRequested();
                var batch = await _dispatcher.ExecuteExportBatchAsync(
                    report,
                    cursor,
                    ExportBatchSize,
                    ct);

                foreach (var row in batch.Items)
                {
                    ct.ThrowIfCancellationRequested();
                    var element = JsonSerializer.SerializeToElement(row, CsvJsonOptions);
                    var values = definition.Columns.Select(column => GetCsvValue(element, column.Key));
                    if (!await TryAppendCsvLineAsync(stream, values, _exportByteLimit, ct))
                    {
                        await stream.DisposeAsync();
                        return new AutoGeneratedReportExportResult(
                            AutoGeneratedReportExecutionStatus.Success,
                            response,
                            SizeLimitExceeded: true);
                    }
                }

                cursor = batch.NextCursor;
            } while (cursor is not null);

            stream.Position = 0;
            return new AutoGeneratedReportExportResult(
                AutoGeneratedReportExecutionStatus.Success,
                response,
                stream);
        }
        catch
        {
            await stream.DisposeAsync();
            throw;
        }
    }

    public async Task<AutoGeneratedReportReconciliationResult> ReconcileWeeklyBccAsync(
        DateOnly reportDate,
        CancellationToken ct = default)
    {
        var tenantIds = (await _tenantSource.ListEligibleTenantIdsAsync(ct))
            .Where(tenantId => tenantId != Guid.Empty)
            .Distinct()
            .ToArray();
        var inserted = 0;
        var existing = 0;
        var failed = 0;
        var date = reportDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);

        foreach (var tenantId in tenantIds)
        {
            ct.ThrowIfCancellationRequested();
            var report = AutoGeneratedReport.Create(
                tenantId,
                $"weekly_bcc_{date}",
                $"Weekly BCC - {reportDate.ToString("MM/dd/yyyy", CultureInfo.InvariantCulture)}",
                reportDate,
                _timeProvider.GetUtcNow().UtcDateTime,
                AutoGeneratedReportDispatcher.CanonicalWeeklyBccPath);

            try
            {
                if (await _reports.EnsureExistsAsync(report, ct))
                    inserted++;
                else
                    existing++;
            }
            catch (OperationCanceledException) when (ct.IsCancellationRequested)
            {
                throw;
            }
            catch (Exception ex)
            {
                failed++;
                _logger.LogError(
                    ex,
                    "Unable to reconcile Weekly BCC metadata for tenant {TenantId} and report date {ReportDate}.",
                    tenantId,
                    date);
            }
        }

        return new AutoGeneratedReportReconciliationResult(
            reportDate,
            tenantIds.Length,
            inserted,
            existing,
            failed);
    }

    private static AutoGeneratedReportResponse ToResponse(AutoGeneratedReport report) =>
        new(
            report.Id,
            report.Code,
            report.Description,
            report.ReportDate,
            DateTime.SpecifyKind(report.CreatedAtUtc, DateTimeKind.Utc),
            report.TenantId,
            report.ApiPath);

    private static string? GetCsvValue(JsonElement row, string key)
    {
        if (!row.TryGetProperty(key, out var value) || value.ValueKind is JsonValueKind.Null or JsonValueKind.Undefined)
            return null;

        return value.ValueKind == JsonValueKind.String
            ? value.GetString()
            : value.GetRawText();
    }

    internal static FileStream CreateExportStream()
    {
        var path = Path.Combine(
            Path.GetTempPath(),
            $"legalsynq-liens-export-{Guid.NewGuid():N}.tmp");
        var options = new FileStreamOptions
        {
            Mode = FileMode.CreateNew,
            Access = FileAccess.ReadWrite,
            Share = FileShare.Read | FileShare.Delete,
            BufferSize = 64 * 1024,
            Options = FileOptions.Asynchronous | FileOptions.DeleteOnClose | FileOptions.SequentialScan,
        };
        if (!OperatingSystem.IsWindows())
            options.UnixCreateMode = UnixFileMode.UserRead | UnixFileMode.UserWrite;

        return new FileStream(path, options);
    }

    internal static async ValueTask<bool> TryAppendCsvLineAsync(
        Stream stream,
        IEnumerable<string?> values,
        long exportByteLimit,
        CancellationToken ct = default)
    {
        var line = string.Join(',', values.Select(EscapeCsvField)) + "\r\n";
        var bytes = Encoding.UTF8.GetBytes(line);
        if (stream.Length + bytes.Length > exportByteLimit)
            return false;

        await stream.WriteAsync(bytes, ct);
        return true;
    }

    internal static string EscapeCsvField(string? value)
    {
        if (value is null)
            return string.Empty;

        var firstSignificant = value.FirstOrDefault(character => !char.IsWhiteSpace(character) && !char.IsControl(character));
        var safeValue = firstSignificant is '=' or '+' or '-' or '@' ? $"'{value}" : value;
        return safeValue.IndexOfAny([',', '"', '\r', '\n']) >= 0
            ? $"\"{safeValue.Replace("\"", "\"\"")}\""
            : safeValue;
    }
}
