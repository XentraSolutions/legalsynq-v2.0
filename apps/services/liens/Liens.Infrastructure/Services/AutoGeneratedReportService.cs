using System.Globalization;
using Liens.Application.DTOs;
using Liens.Application.Interfaces;
using Liens.Application.Repositories;
using Liens.Domain.Entities;
using Microsoft.Extensions.Logging;

namespace Liens.Infrastructure.Services;

public sealed class AutoGeneratedReportService : IAutoGeneratedReportService
{
    private readonly IAutoGeneratedReportRepository _reports;
    private readonly IAutoGeneratedReportTenantSource _tenantSource;
    private readonly IAutoGeneratedReportDispatcher _dispatcher;
    private readonly TimeProvider _timeProvider;
    private readonly ILogger<AutoGeneratedReportService> _logger;

    public AutoGeneratedReportService(
        IAutoGeneratedReportRepository reports,
        IAutoGeneratedReportTenantSource tenantSource,
        IAutoGeneratedReportDispatcher dispatcher,
        TimeProvider timeProvider,
        ILogger<AutoGeneratedReportService> logger)
    {
        _reports = reports;
        _tenantSource = tenantSource;
        _dispatcher = dispatcher;
        _timeProvider = timeProvider;
        _logger = logger;
    }

    public async Task<AutoGeneratedReportPage> ListAsync(
        Guid tenantId,
        int page,
        int pageSize,
        CancellationToken ct = default)
    {
        var (items, totalCount) = await _reports.ListAsync(tenantId, page, pageSize, ct);
        return new AutoGeneratedReportPage(
            items.Select(ToResponse).ToList(),
            page,
            pageSize,
            totalCount);
    }

    public async Task<AutoGeneratedReportExecutionResult> ExecuteAsync(
        Guid tenantId,
        long reportId,
        CancellationToken ct = default)
    {
        if (tenantId == Guid.Empty || reportId <= 0)
            return new AutoGeneratedReportExecutionResult(AutoGeneratedReportExecutionStatus.NotFound);

        var report = await _reports.GetByIdAsync(tenantId, reportId, ct);
        if (report is null)
            return new AutoGeneratedReportExecutionResult(AutoGeneratedReportExecutionStatus.NotFound);

        var response = ToResponse(report);
        if (!_dispatcher.Supports(report.ApiPath))
        {
            return new AutoGeneratedReportExecutionResult(
                AutoGeneratedReportExecutionStatus.UnsupportedPath,
                response);
        }

        var weeklyBcc = await _dispatcher.ExecuteAsync(report, ct);
        return new AutoGeneratedReportExecutionResult(
            AutoGeneratedReportExecutionStatus.Success,
            response,
            weeklyBcc);
    }

    public async Task<AutoGeneratedReportReconciliationResult> ReconcileWeeklyBccAsync(
        DateOnly reportDate,
        CancellationToken ct = default)
    {
        var tenantIds = (await _tenantSource.ListEligibleTenantIdsAsync(ct))
            .Where(tenantId => tenantId != Guid.Empty)
            .Distinct()
            .ToArray();
        var inserted = 0;
        var existing = 0;
        var failed = 0;
        var date = reportDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);

        foreach (var tenantId in tenantIds)
        {
            ct.ThrowIfCancellationRequested();
            var report = AutoGeneratedReport.Create(
                tenantId,
                $"weekly_bcc_{date}",
                $"Weekly BCC - {reportDate.ToString("MM/dd/yyyy", CultureInfo.InvariantCulture)}",
                reportDate,
                _timeProvider.GetUtcNow().UtcDateTime,
                AutoGeneratedReportDispatcher.CanonicalWeeklyBccPath);

            try
            {
                if (await _reports.EnsureExistsAsync(report, ct))
                    inserted++;
                else
                    existing++;
            }
            catch (OperationCanceledException) when (ct.IsCancellationRequested)
            {
                throw;
            }
            catch (Exception ex)
            {
                failed++;
                _logger.LogError(
                    ex,
                    "Unable to reconcile Weekly BCC metadata for tenant {TenantId} and report date {ReportDate}.",
                    tenantId,
                    date);
            }
        }

        return new AutoGeneratedReportReconciliationResult(
            reportDate,
            tenantIds.Length,
            inserted,
            existing,
            failed);
    }

    private static AutoGeneratedReportResponse ToResponse(AutoGeneratedReport report) =>
        new(
            report.Id,
            report.Code,
            report.Description,
            report.ReportDate,
            DateTime.SpecifyKind(report.CreatedAtUtc, DateTimeKind.Utc),
            report.TenantId,
            report.ApiPath);
}
