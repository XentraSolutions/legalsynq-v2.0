using Liens.Application.DTOs;
using Liens.Application.Interfaces;
using Liens.Domain.Entities;

namespace Liens.Infrastructure.Services;

public sealed class AutoGeneratedReportDispatcher : IAutoGeneratedReportDispatcher
{
    public const string CanonicalWeeklyBccPath = "/api/liens/reports/weekly-bcc";
    public const string LegacyWeeklyBccPath = "/report/weekly-bcc";

    private readonly IWeeklyBccReportService _weeklyBcc;

    public AutoGeneratedReportDispatcher(IWeeklyBccReportService weeklyBcc)
    {
        _weeklyBcc = weeklyBcc;
    }

    public bool Supports(string apiPath) =>
        string.Equals(apiPath, CanonicalWeeklyBccPath, StringComparison.Ordinal) ||
        string.Equals(apiPath, LegacyWeeklyBccPath, StringComparison.Ordinal);

    public Task<WeeklyBccReportResult> ExecuteAsync(
        AutoGeneratedReport report,
        CancellationToken ct = default)
    {
        if (!Supports(report.ApiPath))
            throw new InvalidOperationException("The saved report type is not supported.");

        return _weeklyBcc.GetAsync(report.TenantId, report.ReportDate, ct);
    }
}
