            throw new InvalidOperationException("The saved report type is not supported.");

        return _weeklyBcc.GetPageAsync(
            report.TenantId,
            report.ReportDate,
            page,
            pageSize,
            includeTotalCount,
            ct);
    }

    public Task<WeeklyBccExportBatch> ExecuteExportBatchAsync(
        AutoGeneratedReport report,
        WeeklyBccExportCursor? cursor,
        int batchSize,
        CancellationToken ct = default)
