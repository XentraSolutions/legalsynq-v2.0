namespace Liens.Domain.Entities;

public sealed class AutoGeneratedReport
{
    public long Id { get; private set; }
    public Guid TenantId { get; private set; }
    public string Code { get; private set; } = string.Empty;
    public string Description { get; private set; } = string.Empty;
    public DateOnly ReportDate { get; private set; }
    public DateTime CreatedAtUtc { get; private set; }
    public string ApiPath { get; private set; } = string.Empty;

    private AutoGeneratedReport() { }

    public static AutoGeneratedReport Create(
        Guid tenantId,
        string code,
        string description,
        DateOnly reportDate,
        DateTime createdAtUtc,
        string apiPath)
    {
        if (tenantId == Guid.Empty)
            throw new ArgumentException("TenantId is required.", nameof(tenantId));
        ArgumentException.ThrowIfNullOrWhiteSpace(code);
        ArgumentException.ThrowIfNullOrWhiteSpace(description);
        ArgumentException.ThrowIfNullOrWhiteSpace(apiPath);

        return new AutoGeneratedReport
        {
            TenantId = tenantId,
            Code = code.Trim(),
            Description = description.Trim(),
            ReportDate = reportDate,
            CreatedAtUtc = DateTime.SpecifyKind(createdAtUtc, DateTimeKind.Utc),
            ApiPath = apiPath.Trim(),
        };
    }
}
