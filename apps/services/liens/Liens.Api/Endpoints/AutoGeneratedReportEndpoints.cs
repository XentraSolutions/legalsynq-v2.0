namespace Liens.Api.Endpoints;

public static class AutoGeneratedReportEndpoints
{
    private const int DefaultPageSize = 50;
    private const int MaximumPageSize = 100;

    public static void MapAutoGeneratedReportEndpoints(this WebApplication app)
    {
        var canonical = app.MapGroup("/api/liens/reports/auto-generated")
            .RequireAuthorization(Policies.AuthenticatedUser)
            .RequireProductAccess(LiensPermissions.ProductCode);
        MapRoutes(canonical);

        var legacy = app.MapGroup("/report/auto-generated")
            .RequireAuthorization(Policies.AuthenticatedUser)
            .RequireProductAccess(LiensPermissions.ProductCode);
        MapRoutes(legacy);
    }

    private static void MapRoutes(RouteGroupBuilder group)
    {
        group.MapGet(string.Empty, ListReports)
            .RequirePermission(LiensPermissions.CaseRead);
        group.MapPost("/{reportId:long}/execute", ExecuteReport)
            .RequirePermission(LiensPermissions.CaseRead);
        group.MapPost("/{reportId:long}/export", ExportReport)
            .RequirePermission(LiensPermissions.CaseRead);
    }

    private static async Task<IResult> ListReports(
        IAutoGeneratedReportService service,
        ICurrentRequestContext context,
        HttpContext httpContext,
        CancellationToken ct,
        int page = 1,
        int pageSize = DefaultPageSize)
    {
        httpContext.Response.Headers.CacheControl = "no-store";
        if (page < 1 || pageSize < 1 || pageSize > MaximumPageSize)
        {
            return Results.BadRequest(new
            {
                isSuccess = false,
                message = $"page must be at least 1 and pageSize must be between 1 and {MaximumPageSize}.",
            });
        }

        var tenantId = CaseEndpoints.RequireTenantId(context);
        var result = await service.ListAsync(tenantId, page, pageSize, ct);
        return Results.Ok(new
        {
            isSuccess = true,
            message = "Auto-generated reports retrieved.",
            result.Page,
            result.PageSize,
            result.TotalCount,
            data = result.Items,
        });
    }

    private static async Task<IResult> ExecuteReport(
        long reportId,
        IAutoGeneratedReportService service,
        ICurrentRequestContext context,
        HttpContext httpContext,
        CancellationToken ct,
        int page = 1,
        int pageSize = DefaultPageSize)
    {
        httpContext.Response.Headers.CacheControl = "no-store";
        if (page < 1 || pageSize < 1 || pageSize > MaximumPageSize)
        {
            return Results.BadRequest(new
            {
                isSuccess = false,
                message = $"page must be at least 1 and pageSize must be between 1 and {MaximumPageSize}.",
            });
        }

        var tenantId = CaseEndpoints.RequireTenantId(context);
        var result = await service.ExecuteAsync(tenantId, reportId, page, pageSize, ct);

        if (result.Status == AutoGeneratedReportExecutionStatus.NotFound)
        {
            return Results.NotFound(new
            {
                isSuccess = false,
                message = "Auto-generated report not found.",
            });
        }

        if (result.Status == AutoGeneratedReportExecutionStatus.UnsupportedPath)
        {
            return Results.Conflict(new
            {
                isSuccess = false,
                message = "The saved report type is not supported.",
            });
        }

        var weeklyBcc = result.WeeklyBcc!;
        var definition = result.Definition!;
        var totalPages = weeklyBcc.TotalCount == 0
            ? 0
            : ((weeklyBcc.TotalCount - 1) / weeklyBcc.PageSize) + 1;
        return Results.Ok(new
        {
            isSuccess = true,
            message = "Weekly BCC report generated.",
            report = result.Report,
            definition.ReportType,
            definition.SchemaVersion,
            asOfDate = weeklyBcc.AsOfDate,
            weeklyBcc.Page,
            weeklyBcc.PageSize,
            totalPages,
            weeklyBcc.TotalCount,
            summaryTotals = weeklyBcc.SummaryTotals,
            definition.Columns,
            data = weeklyBcc.Items,
        });
    }

    private static async Task<IResult> ExportReport(
        long reportId,
        IAutoGeneratedReportService service,
        AutoGeneratedReportExportConcurrencyLimiter concurrencyLimiter,
        IOptions<AutoGeneratedReportOptions> options,
        ICurrentRequestContext context,
        HttpContext httpContext,
        CancellationToken ct)
    {
        httpContext.Response.Headers.CacheControl = "no-store";
        var tenantId = CaseEndpoints.RequireTenantId(context);
        var lease = concurrencyLimiter.TryAcquire();
        if (lease is null)
        {
            httpContext.Response.Headers.RetryAfter = "5";
            return Results.Json(
                new
                {
                    isSuccess = false,
                    message = "The export service is busy. Try again shortly.",
                    error = new { code = "too_many_requests" },
                },
                statusCode: StatusCodes.Status429TooManyRequests);
        }

        AutoGeneratedReportExportResult result;
        try
        {
            result = await service.ExportAsync(tenantId, reportId, ct);
        }
        catch
        {
            lease.Dispose();
            throw;
        }

        if (result.Status == AutoGeneratedReportExecutionStatus.NotFound)
        {
            await DisposeExportAsync(result, lease);
            return Results.NotFound(new
            {
                isSuccess = false,
                message = "Auto-generated report not found.",
            });
        }

        if (result.Status == AutoGeneratedReportExecutionStatus.UnsupportedPath)
        {
            await DisposeExportAsync(result, lease);
            return Results.Conflict(new
            {
                isSuccess = false,
                message = "The saved report type is not supported.",
            });
        }

        if (result.SizeLimitExceeded)
        {
            await DisposeExportAsync(result, lease);
            return Results.BadRequest(new
            {
                isSuccess = false,
                message = GetExportSizeLimitExceededMessage(options.Value.ExportSizeLimitMiB),
                error = new { code = "validation_error" },
            });
        }

        var report = result.Report!;
        var filename = $"weekly_bcc_{report.Date:yyyyMMdd}.csv";
        return new Base64CsvJsonResult(result, filename, lease);
    }

    internal static string GetExportSizeLimitExceededMessage(int exportSizeLimitMiB) =>
        $"Export exceeds the configured {exportSizeLimitMiB} MiB file size limit.";

    private static async ValueTask DisposeExportAsync(
        AutoGeneratedReportExportResult export,
        IDisposable lease)
    {
        try
        {
            await export.DisposeAsync();
        }
        finally
        {
            lease.Dispose();
        }
    }

    internal sealed class Base64CsvJsonResult(
        AutoGeneratedReportExportResult export,
        string filename,
        IDisposable lease) : IResult
    {
        private const string Prefix =
            "{\"isSuccess\":true,\"message\":\"CSV generated successfully.\",\"data\":[{\"base64\":\"";

        public async Task ExecuteAsync(HttpContext httpContext)
        {
            using (lease)
            {
                await using (export)
                {
                    var content = export.Content
                        ?? throw new InvalidOperationException("Successful export content is required.");
                    var suffix =
                        $"\",\"filename\":{JsonSerializer.Serialize(filename)},\"export_format\":\"csv\"}}]}}";
                    var prefixBytes = Encoding.UTF8.GetBytes(Prefix);
                    var suffixBytes = Encoding.UTF8.GetBytes(suffix);
                    var base64Length = 4L * ((content.Length + 2L) / 3L);
                    var response = httpContext.Response;
                    var ct = httpContext.RequestAborted;

                    response.StatusCode = StatusCodes.Status200OK;
                    response.ContentType = "application/json; charset=utf-8";
                    response.ContentLength = prefixBytes.Length + base64Length + suffixBytes.Length;
                    await response.Body.WriteAsync(prefixBytes, ct);

                    await WriteBase64Async(content, response.Body, ct);
                    await response.Body.WriteAsync(suffixBytes, ct);
                }
            }
        }
    }

    internal static async Task WriteBase64Async(
        Stream source,
        Stream destination,
        CancellationToken ct = default)
    {
        const int readSize = 64 * 1024;
        var input = ArrayPool<byte>.Shared.Rent(readSize + 2);
        var output = ArrayPool<byte>.Shared.Rent(Base64.GetMaxEncodedToUtf8Length(readSize + 2));
        var buffered = 0;

        try
        {
            while (true)
            {
                var read = await source.ReadAsync(input.AsMemory(buffered, readSize), ct);
                if (read == 0)
                    break;

                var available = buffered + read;
                var encodable = available - (available % 3);
                if (encodable > 0)
                {
                    var status = Base64.EncodeToUtf8(
                        input.AsSpan(0, encodable),
                        output,
                        out var consumed,
                        out var written,
                        isFinalBlock: false);
                    if (status != OperationStatus.Done || consumed != encodable)
                        throw new InvalidOperationException("Unable to encode the CSV export.");

                    await destination.WriteAsync(output.AsMemory(0, written), ct);
                }

                buffered = available - encodable;
                input.AsSpan(encodable, buffered).CopyTo(input);
            }

            var finalStatus = Base64.EncodeToUtf8(
                input.AsSpan(0, buffered),
                output,
                out var finalConsumed,
                out var finalWritten,
                isFinalBlock: true);
            if (finalStatus != OperationStatus.Done || finalConsumed != buffered)
                throw new InvalidOperationException("Unable to finalize the CSV export encoding.");

            await destination.WriteAsync(output.AsMemory(0, finalWritten), ct);
        }
        finally
        {
            ArrayPool<byte>.Shared.Return(input);
            ArrayPool<byte>.Shared.Return(output);
        }
    }
}

internal sealed class AutoGeneratedReportExportConcurrencyLimiter
{
    private readonly SemaphoreSlim _semaphore;

    public AutoGeneratedReportExportConcurrencyLimiter(IOptions<AutoGeneratedReportOptions> options)
    {
        _semaphore = new SemaphoreSlim(
            options.Value.MaximumConcurrentExports,
            options.Value.MaximumConcurrentExports);
    }

    public IDisposable? TryAcquire() =>
        _semaphore.Wait(0) ? new Lease(_semaphore) : null;

    private sealed class Lease(SemaphoreSlim semaphore) : IDisposable
    {
        private SemaphoreSlim? _semaphore = semaphore;

        public void Dispose() =>
            Interlocked.Exchange(ref _semaphore, null)?.Release();
    }
}
